"""
Generates docs/API_DOCUMENTATION.md and docs/DATABASE_SCHEMA.md directly from
the source code (pure `ast` parsing -- no Flask/SQLAlchemy needed), so the
reference docs can't drift from what the code actually does.

Usage (from backend/):
    python scripts/generate_docs.py
"""

import ast
import glob
import os
import re
from pathlib import Path

BACKEND = Path(__file__).resolve().parent.parent
DOCS = BACKEND.parent / "docs"

ROUTE_FILES = sorted(glob.glob(str(BACKEND / "app" / "routes" / "*.py"))) + [
    str(BACKEND / "app" / "ghost_routes.py"),
    str(BACKEND / "attack_routes.py"),
]


def _url_prefixes():
    """blueprint variable -> url_prefix, read from app/__init__.py."""
    src = (BACKEND / "app" / "__init__.py").read_text()
    return {m.group(1): m.group(2) for m in re.finditer(r'register_blueprint\((\w+),\s*url_prefix="([^"]*)"\)', src)}


def _auth_label(func_src: str, decorators: list[str]) -> str:
    perm = None
    for d in decorators:
        m = re.match(r"require_permission\(['\"]([^'\"]+)['\"]\)", d)
        if m:
            perm = m.group(1)
    if perm:
        return f"permission: `{perm}`"
    if any(d.startswith("require_role") or d == "require_admin" for d in decorators):
        return "role: admin"
    if "_require_admin(" in func_src or 'role != "admin"' in func_src or "_is_admin(" in func_src:
        return "admin (inline check)"
    if "_is_admin_or_hr(" in func_src:
        return "manager/admin (inline check)"
    if any(d.startswith("jwt_required") for d in decorators):
        return "any authenticated user"
    return "public"


def api_doc() -> str:
    prefixes = _url_prefixes()
    rows = []
    for path in ROUTE_FILES:
        text = Path(path).read_text()
        tree = ast.parse(text)
        for node in ast.walk(tree):
            if not isinstance(node, ast.FunctionDef):
                continue
            decorators = [ast.unparse(d) for d in node.decorator_list]
            for d in node.decorator_list:
                if isinstance(d, ast.Call) and isinstance(d.func, ast.Attribute) and d.func.attr == "route":
                    bp_name = d.func.value.id
                    route = d.args[0].value
                    methods = ["GET"]
                    for kw in d.keywords:
                        if kw.arg == "methods":
                            methods = [e.value for e in kw.value.elts]
                    prefix = prefixes.get(bp_name, "/api")
                    doc = (ast.get_docstring(node) or "").strip().split("\n\n")[0].replace("\n", " ")
                    rows.append((
                        prefix + route,
                        ",".join(methods),
                        _auth_label(ast.get_source_segment(text, node) or "", decorators),
                        Path(path).stem,
                        doc[:160],
                    ))
    rows.sort(key=lambda r: (r[3], r[0], r[1]))

    out = [
        "# API Documentation",
        "",
        "_Generated by `backend/scripts/generate_docs.py` directly from the route decorators -- regenerate rather than hand-edit._",
        "",
        "All endpoints are JSON. Authenticated endpoints expect `Authorization: Bearer <JWT>` (obtained from `POST /api/auth/login`).",
        "Errors are always `{\"error\": \"<message>\"}`; success confirmations use `{\"message\": \"...\"}`.",
        "Common statuses: `400` validation, `401` missing/expired token, `403` role or permission denied, `404` not found, `413` request too large (8 MB cap), `429` login rate limit.",
        "",
        f"**{len(rows)} endpoints.**",
        "",
    ]
    current = None
    for url, methods, auth, module, doc in rows:
        if module != current:
            current = module
            out += ["", f"## {module}", "", "| Method | Path | Access | Notes |", "|---|---|---|---|"]
        out.append(f"| {methods} | `{url}` | {auth} | {doc} |")
    out.append("")
    return "\n".join(out)


def _col_type(call: ast.Call) -> str:
    if not call.args:
        return "?"
    first = call.args[0]
    if isinstance(first, ast.Constant) and isinstance(first.value, str) and len(call.args) > 1:
        first = call.args[1]  # Column("metadata", db.Text) form
    return ast.unparse(first).replace("db.", "")


def schema_doc() -> str:
    out = [
        "# Database Schema",
        "",
        "_Generated by `backend/scripts/generate_docs.py` from the SQLAlchemy models._",
        "",
        "SQLite for the capstone prototype (`DATABASE_URL`, default `sqlite:///secureai.db`). Tables are created by `db.create_all()`; columns added after the first release are applied by idempotent `_ensure_*` helpers in `app/__init__.py` (there is no Alembic).",
        "",
    ]
    for path in sorted(glob.glob(str(BACKEND / "app" / "models" / "*.py"))):
        if path.endswith("__init__.py"):
            continue
        text = Path(path).read_text()
        tree = ast.parse(text)
        for node in tree.body:
            if isinstance(node, ast.ClassDef):
                table = None
                cols = []
                for item in node.body:
                    if isinstance(item, ast.Assign) and isinstance(item.targets[0], ast.Name):
                        name = item.targets[0].id
                        if name == "__tablename__":
                            table = item.value.value
                        elif isinstance(item.value, ast.Call) and ast.unparse(item.value.func) == "db.Column":
                            call = item.value
                            kw = {k.arg: ast.unparse(k.value) for k in call.keywords}
                            notes = []
                            if kw.get("primary_key") == "True":
                                notes.append("PK")
                            if kw.get("unique") == "True":
                                notes.append("unique")
                            if kw.get("nullable") == "False":
                                notes.append("not null")
                            if kw.get("index") == "True":
                                notes.append("indexed")
                            for a in call.args:
                                if isinstance(a, ast.Call) and ast.unparse(a.func) == "db.ForeignKey":
                                    notes.append("FK -> " + a.args[0].value)
                            if "default" in kw:
                                notes.append("default")
                            cols.append((name, _col_type(call), ", ".join(notes)))
                if table and cols:
                    doc = (ast.get_docstring(node) or "").strip().split("\n\n")[0].replace("\n", " ")
                    out += [f"## `{table}` ({node.name})", ""]
                    if doc:
                        out += [doc[:300], ""]
                    out += ["| Column | Type | Notes |", "|---|---|---|"]
                    out += [f"| {c} | {t} | {n} |" for c, t, n in cols]
                    out.append("")
    return "\n".join(out)


if __name__ == "__main__":
    DOCS.mkdir(exist_ok=True)
    (DOCS / "API_DOCUMENTATION.md").write_text(api_doc())
    (DOCS / "DATABASE_SCHEMA.md").write_text(schema_doc())
    print("wrote docs/API_DOCUMENTATION.md and docs/DATABASE_SCHEMA.md")
